// Dev-mode completeness check: warn if any key in `en` is missing or empty in `zh`
if (import.meta.env?.DEV) {
  const enKeys = Object.keys(translations.en) as TranslationKey[];
  for (const key of enKeys) {
    const zhVal = (translations.zh as Record<string, string>)[key];
    if (!zhVal || zhVal.trim() === '') {
      console.warn(`[i18n] Missing Chinese translation for key: "${key}"`);
    }
  }
}

